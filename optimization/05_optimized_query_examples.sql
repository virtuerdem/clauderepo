-- Create a reusable function for date calculations
CREATE OR REPLACE FUNCTION GET_REPORT_DATE_RANGE(
    p_days_back IN NUMBER DEFAULT 1
) RETURN SYS_REFCURSOR IS
    v_cursor SYS_REFCURSOR;
BEGIN
    OPEN v_cursor FOR
        SELECT
            TRUNC(SYSDATE - p_days_back) AS start_date,
            TRUNC(SYSDATE - p_days_back) + 23/24 AS end_date,
            TRUNC(SYSDATE - p_days_back - 19) AS rolling_start_date
        FROM DUAL;

    RETURN v_cursor;
END;
/

