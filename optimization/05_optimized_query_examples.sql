    MAX(CASE WHEN day_offset = 9 THEN AVG_JITTER END) AS CONG_12,
    MAX(CASE WHEN day_offset = 8 THEN AVG_JITTER END) AS CONG_13,
    MAX(CASE WHEN day_offset = 7 THEN AVG_JITTER END) AS CONG_14,
    MAX(CASE WHEN day_offset = 6 THEN AVG_JITTER END) AS CONG_15,
    MAX(CASE WHEN day_offset = 5 THEN AVG_JITTER END) AS CONG_16,
    MAX(CASE WHEN day_offset = 4 THEN AVG_JITTER END) AS CONG_17,
    MAX(CASE WHEN day_offset = 3 THEN AVG_JITTER END) AS CONG_18,
    MAX(CASE WHEN day_offset = 2 THEN AVG_JITTER END) AS CONG_19,
    MAX(CASE WHEN day_offset = 1 THEN AVG_JITTER END) AS CONG_20,
    A.AVAILABILITY_PCT AS AVAILABILITY_SYS
FROM
    AGG_TWAMP_JITTER_DAILY T
JOIN
    AGG_CELL_AVAILABILITY_DAILY_4G A
    ON T.ENODEB_ID = A.ENODEB_ID
    AND T.AGGREGATION_DATE = A.AGGREGATION_DATE
CROSS JOIN
    (SELECT TRUNC(SYSDATE-1) - LEVEL AS calc_date, LEVEL AS day_offset
     FROM DUAL CONNECT BY LEVEL <= 20) dates
WHERE
    T.AGGREGATION_DATE = dates.calc_date
    AND T.SUB_REGION_ID IN (1204)
    AND A.AGGREGATION_DATE = TRUNC(SYSDATE-1)
GROUP BY
    T.CITY_NAME, T.ENODEB_NAME, A.AVAILABILITY_PCT
HAVING
    MAX(CASE WHEN day_offset = 1 THEN AVG_JITTER END) > 10
ORDER BY 1, 2;

